// Preserve source identities for scene queries; timings follow the actual Russian words.
const spoken = (s:string) => s.replace(/ChatGPT/gi,'Чат-джи-пи-ти').replace(/Sydney/gi,'Сидни').replace(/NVIDIA/gi,'Нвидии').replace(/Chinchilla/gi,'Шиншиллой').replace(/GPU/gi,'джи-пи-ю').replace(/RLHF/gi,'Эр-эл-эйч-эф').replace(/Loom/gi,'Лум').replace(/FLOPS/gi,'флопс').replace(/[^а-яёa-z0-9]/gi,'').toLowerCase();
export function localizedLyrics(source: Lyrics, recording: Lyrics, toSource:(t:number)=>number): Lyrics {
 return new Lyrics({lines:source.lines.map((l,i)=>{
   const real=recording.lines[i]!;
   const chars=real.words.flatMap(w=>Array.from(spoken(w.w),()=>w));
   let at=0;
   const words=l.words.map((w,j)=>{
     const display=slots[i]![j] || '\u2009';
     const n=display==='AGI'?0:spoken(display).length;
     const a=chars[Math.min(at,chars.length-1)]!, b=chars[Math.min(at+Math.max(0,n-1),chars.length-1)]!;
     at+=n;
     return {...w,source:w.w,w:display,start:toSource(a.start),end:toSource(n?b.end:a.start),syl:undefined};
   });
   return {...l,source:l.text,text:slots[i]!.map(s=>s || '\u2009').join(' '),words};
 })});
}
